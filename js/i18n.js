let lang = 'ro';

export function setLang(l) {
  lang = STRINGS[l] ? l : 'en';
  document.documentElement.lang = lang;
}

export function getLang() {
  return lang;
}

export function detectLang() {
  try {
    return (navigator.language || 'en').toLowerCase().startsWith('ro') ? 'ro' : 'en';
  } catch {
    return 'en';
  }
}

/** Translate a UI key, filling {placeholders}. */
export function t(key, vars) {
  let s = STRINGS[lang][key] ?? STRINGS.en[key] ?? key;
  if (vars) for (const k in vars) s = s.replaceAll(`{${k}}`, vars[k]);
  return s;
}

/** Pick the current language from a {en, ro} value; plain strings pass through. */
export function tx(v) {
  if (v == null) return '';
  if (typeof v === 'string') return v;
  return v[lang] ?? v.en ?? v.ro ?? '';
}

/** Same as tx for arrays of localized values. */
export function txList(list) {
  return (list || []).map(tx).filter(Boolean);
}

